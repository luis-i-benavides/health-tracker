import Foundation

/// Whether medication and measurement alarms are on, and how they ring. While alarms are on,
/// they're kept in sync with the schedule automatically and notifications become silent.
struct AlarmSettings: Codable, Equatable {
    var isEnabled = false
    var snoozeMinutes = AlarmSettings.defaultSnoozeMinutes
    var sound = AlarmSound.chime

    static let standard = AlarmSettings()
    /// Snooze lengths offered to the user, in minutes (9 matches the Clock app).
    static let snoozeOptions = [5, 9, 10, 15, 30]
    static let defaultSnoozeMinutes = 9
}

/// Sounds an alarm can play. Apps can't use the Clock app's ringtones, so besides the system
/// default these are files bundled in `Sounds` (generated by `Scripts/make_alarm_sounds.py`).
enum AlarmSound: String, CaseIterable, Identifiable, Codable {
    case systemDefault, chime, classic, gentle, pulse

    var id: String { rawValue }

    var label: String {
        switch self {
        case .systemDefault: "Default"
        case .chime: "Chime"
        case .classic: "Classic"
        case .gentle: "Gentle Rise"
        case .pulse: "Pulse"
        }
    }

    /// The bundled file, or `nil` for the system default.
    var fileName: String? {
        self == .systemDefault ? nil : "alarm-\(rawValue).caf"
    }
}
